/* Найти музей по адресу (slug). */
function getMuseum(slug) {
  return MUSEUMS.find(function (m) {
    return m.slug === slug;
  });
}

/* Название категории по ключу. */
function categoryLabel(key) {
  return CATEGORIES[key] || "Музей";
}
